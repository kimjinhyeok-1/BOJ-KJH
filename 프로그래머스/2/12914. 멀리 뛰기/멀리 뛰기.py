"""
 전형적인 DP 문제
 마지막에 결국 선택할 수 있는 것은 1칸 아니면 두칸
 DP에서 중요한 것은 두 가지
 1. 초깃값 설정
 2. 점화식 설정
 
 dp[n] : n칸까지 왔을 때 올 수 있는 경우의 수라고 가정
 초깃값은 
 dp[0] = 1
 dp[1] = 1
 dp[n] = dp[n-2] + dp[n-1] 
 
 Ex) dp[5]는 3까지 왔을 때 올 수 있는 경우의 수 + 4까지 왔을 때 올 수 있는 경우의 수
 
"""

def solution(n):
    dp = [0] * (n+1)
    dp[0] = 1
    if n >= 1: dp[1] = 1
    
    for i in range(2, n+1):
        dp[i] = (dp[i-1] + dp[i-2]) % 1234567
        
    return dp[n]